"""Wave-CAIPI TSE reconstruction from Siemens TWIX data with NIfTI export.

Author: Yiyun Dong
Affiliation: Athinoula A. Martinos Center for Biomedical Imaging
License: MIT License

Description:
    Reconstruct one MB1 or MB2 TSE acquisition generated by
    ``seq/tse_2d_wave_mb1.m`` or ``seq/tse_2d_wave_mb2v_v3.m``. A separately
    acquired mixed-dimension FLASH calibration
    (``seq/gre_mixed_dim_mb2_calibration.m``) supplies the receive-noise
    whitener, one coil-compression basis, independent 2D ESPIRiT sensitivities
    for every physical slice and, for Wave data, the y/z Wave point-spread
    function (PSF).

    Stages (each stage includes the previous ones):
      audit        Validate TWIX headers, sequence signatures, sidecars, ADC
                   chronology, sampled trajectories and the raw-slice to
                   physical-slice mapping. No sample arrays are reconstructed.
      calibration  Noise whitening and coil compression, slice-wise ESPIRiT
                   maps and the Wave PSF fit.
      recon        Group-wise reconstruction, assembled complex volume and
                   magnitude/phase NIfTI export with exact readback.

    MB1 data must form a complete no-Wave Cartesian grid; each slice is the
    exact least-squares coil combination. MB2 data are solved per SMS group
    with lambda-0 CG-SENSE through the MB2 Wave operator, after real-grid
    adjoint and synthetic-recovery tests. With ``--l1-threshold-multiple``,
    MB2 groups are also solved with L1-wavelet FISTA, starting from lambda 0,
    with band weights scaled by the measured noise of this scan.

Notes:
    - Every output file is written exclusively; nothing is overwritten.
      Rerunning with the same inputs and settings resumes from the saved
      checkpoints. A calibration or output folder that already holds results
      of other inputs or settings is rejected.
    - The calibration folder can be shared by every TSE scan that used the
      same calibration acquisition.
    - Only transverse prescriptions are supported, matching the validated
      slice-direction and NIfTI conventions.
"""

