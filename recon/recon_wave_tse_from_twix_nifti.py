def main():
    """Validate the inputs, prepare the shared calibration and reconstruct one TSE scan.

    Command-line arguments are described by ``--help``. Writes typed
    subfolders below ``--calibration-dir`` and ``--output-dir``; see the module
    docstring for the stages. Raises ValueError or RuntimeError when an input
    contract, numerical gate or output-folder check fails.
    """
    args = parse_arguments()
    if args.threads is not None:
        torch.set_num_threads(args.threads)
        torch.set_num_interop_threads(1)
    inputs = resolve_inputs(args)
    calibration_folders = output_folders(args.calibration_dir)
    folders = output_folders(args.output_dir)
    start_log(folders)
    for path in (calibration_folders["arrays"], folders["arrays"]):
        require_free_space(path, args.min_free_gib)
    if args.device.startswith("cuda") and not torch.cuda.is_available():
        raise RuntimeError("--device cuda was requested but CUDA is not available")

    # Provenance: identical inputs and settings are required to reuse a folder.
    # Wave PSF fits are tagged by their settings and may coexist in one calibration folder.
    calibration_settings = {"virtual_coils": args.virtual_coils,
                            "espirit_calib_width": ESPIRIT_CALIB_WIDTH, "espirit_crop": ESPIRIT_CROP}
    ensure_json(calibration_folders["reports"] / "input_manifest.json",
                {"calibration": describe_inputs(inputs["calibration"]), "settings": calibration_settings})
    ensure_json(folders["reports"] / "input_manifest.json",
                {"tse": describe_inputs(inputs["tse"]),
                 "calibration_dir": str(calibration_folders["reports"].parent),
                 "calibration_settings": calibration_settings,
                 "settings": {"solver": SOLVER_TAG, "max_iterations": args.max_iterations,
                              "tolerance": args.tolerance, "psf_fit_range": args.psf_fit_range,
                              "psf_low_amplitude_c_fallback": args.psf_low_amplitude_c_fallback,
                              "allow_missing_final_adcs": args.allow_missing_final_adcs}})
    record_source_digest(folders)

    # Calibration: sidecar contract and header only; no sample arrays yet.
    meta = load_compact_metadata(inputs["calibration"]["labels"])
    calibration_scan = open_twix(inputs["calibration"]["twix"])
    record_index = index_compact_streams(calibration_scan, meta)
    geometry = header_contract(calibration_scan, inputs["calibration"]["seq"], meta)
    cal_encoding = audit_calibration(inputs["calibration"], calibration_scan, record_index,
                                     meta, calibration_folders)
    tse_scan = open_twix(inputs["tse"]["twix"])
    encoding, audit = audit_tse(inputs["tse"], tse_scan, meta, geometry, cal_encoding, folders,
                                args.allow_missing_final_adcs)
    LOGGER.info("Audit passed: MB%d, Ry %d, Wave %s, %d groups",
                audit["MB"], audit["Ry"], audit["wave"], len(encoding["pairs"]))
    if args.l1_threshold_multiple is not None:
        check_l1_support(audit, meta, args.l1_wavelet_levels)
    if args.stage == "audit":
        return

    basis, whitener = prepare_common_basis(inputs["calibration"], calibration_scan, record_index,
                                           meta, calibration_folders, args.virtual_coils)
    estimate_maps(inputs["calibration"], calibration_scan, record_index, meta, basis, calibration_folders,
                  args.csm_device, args.csm_workers)
    psf_fit = None
    if audit["wave"]:
        psf_fit = prepare_psf(calibration_scan, record_index, meta, cal_encoding, calibration_folders,
                              whitener, args.psf_fit_range, args.psf_low_amplitude_c_fallback)
    if args.stage == "calibration":
        return

    if audit["MB"] == 1:
        verify_mb1_calibration_mapping(tse_scan, basis, meta, calibration_folders, folders, encoding)
    image, reports = reconstruct_groups(tse_scan, meta, basis, calibration_folders, folders, encoding,
                                        cal_encoding, psf_fit, audit, args)
    nifti = export_volume(image, tse_scan, audit, folders, SOLVER_TAG)
    residuals = [r["relative_data_residual"] for r in reports]
    ensure_json(folders["reports"] / f"{SOLVER_TAG}_completed.json", {
        "groups": len(reports), "shape": list(image.shape), "voxel_size_mm": audit["voxel_mm"],
        "volume_sha256": digest(folders["arrays"] / f"{SOLVER_TAG}_complex_physical_slices.npy"),
        "relative_data_residual_min_median_max": [min(residuals), float(np.median(residuals)),
                                                  max(residuals)],
        "nifti": nifti, "calibration_dir": str(calibration_folders["reports"].parent)})
    LOGGER.info("Reconstruction complete: %s", nifti["magnitude"])
    if args.l1_threshold_multiple is not None:
        reconstruct_l1(tse_scan, meta, basis, calibration_folders, folders, encoding, cal_encoding,
                       psf_fit, audit, args, image)


def parse_arguments():
    """Return the parsed command-line arguments.

    Returns:
        argparse.Namespace: Input/output paths, stage, device and solver
        settings. Raises SystemExit through argparse on invalid values.
    """
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0],
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    group = parser.add_argument_group("calibration inputs")
    group.add_argument("--calibration-twix", type=Path, required=True,
                       help="Mixed FLASH calibration TWIX .dat file.")
    group.add_argument("--calibration-seq", type=Path, required=True,
                       help="Pulseq .seq file of the calibration.")
    group.add_argument("--calibration-labels", type=Path,
                       help="Calibration *_geometry_labels.mat sidecar "
                            "(default: <seq stem>_geometry_labels.mat beside the .seq).")
    group = parser.add_argument_group("TSE inputs")
    group.add_argument("--tse-twix", type=Path, required=True, help="TSE TWIX .dat file.")
    group.add_argument("--tse-seq", type=Path, required=True, help="Pulseq .seq file of the TSE.")
    group.add_argument("--tse-peorder", type=Path,
                       help="TSE *_PEorder.mat sidecar (default: <seq stem>_PEorder.mat beside the "
                            ".seq, in its metadata/ folder, or one level up).")
    group = parser.add_argument_group("outputs")
    group.add_argument("--calibration-dir", type=Path, required=True,
                       help="Folder for calibration products; reusable by every TSE scan of the "
                            "same calibration acquisition.")
    group.add_argument("--output-dir", type=Path, required=True,
                       help="Folder for the products of this TSE scan.")
    group = parser.add_argument_group("processing")
    group.add_argument("--stage", choices=("audit", "calibration", "recon"), default="recon",
                       help="Last stage to run (default: recon, i.e. everything).")
    group.add_argument("--device", default="cpu", help="Torch device of the TSE solver (cpu or cuda).")
    group.add_argument("--csm-device", type=int, default=-1,
                       help="SigPy device of ESPIRiT: -1 for CPU, a GPU index otherwise (needs CuPy).")
    group.add_argument("--csm-workers", type=int, default=1,
                       help="Parallel single-threaded CPU processes for ESPIRiT, one slice each "
                            "(default: 1, serial).")
    group.add_argument("--threads", type=int, help="CPU threads for PyTorch (default: PyTorch's choice).")
    group.add_argument("--virtual-coils", type=int, default=20,
                       help="Number of compressed virtual coils (default: 20).")
    group.add_argument("--max-iterations", type=int, default=800,
                       help="CG-SENSE iteration budget per MB2 group (default: 800).")
    group.add_argument("--tolerance", type=float, default=1e-6,
                       help="Relative CG-SENSE residual tolerance (default: 1e-6).")
    group.add_argument("--psf-fit-range", type=int, nargs=2, metavar=("START", "STOP"),
                       help="Reviewed readout-sample interval [START, STOP) for the Wave PSF fit, "
                            "validated on held-out samples; default: automatic interval.")
    group.add_argument("--psf-low-amplitude-c-fallback", action="store_true",
                       help="Allow the frequency-locked fit of a low-amplitude constant Wave phase.")
    group.add_argument("--allow-missing-final-adcs", type=int, default=0,
                       help="Accept a TSE TWIX file that ends this many ADCs early; the missing "
                            "lines are treated as unsampled (default: 0).")
    group.add_argument("--min-free-gib", type=float, default=10,
                       help="Stop before writing when the output filesystem has less free space.")
    group = parser.add_argument_group("L1-wavelet regularization (MB2 only)")
    group.add_argument("--l1-threshold-multiple", type=float, metavar="C",
                       help="Also reconstruct with L1-wavelet FISTA at lambda_b = C * sigma_b * mean "
                            "diag(A^H A)_b, where sigma_b is the lambda-0 noise RMS of band b "
                            "(C = 0.5 on the TerraX R2x4 scan); default: lambda 0 only.")
    group.add_argument("--l1-wavelet-levels", type=int, default=L1_DEFAULT_LEVELS,
                       help="Periodized db4 levels; both native matrix sizes must be divisible by "
                            f"2**levels (default: {L1_DEFAULT_LEVELS}).")
    group.add_argument("--l1-max-iterations", type=int, default=L1_DEFAULT_MAX_ITERATIONS,
                       help=f"FISTA iteration budget per group (default: {L1_DEFAULT_MAX_ITERATIONS}).")
    group.add_argument("--l1-tolerance", type=float, default=L1_DEFAULT_TOLERANCE,
                       help="FISTA stops when the relative image change falls below this value "
                            f"(default: {L1_DEFAULT_TOLERANCE:g}).")
    args = parser.parse_args()
    if args.virtual_coils < 1 or args.max_iterations < 1 or args.allow_missing_final_adcs < 0:
        parser.error("Virtual coils and iterations must be positive; missing ADCs nonnegative")
    if not 0 < args.tolerance < 1:
        parser.error("--tolerance must lie in (0, 1)")
    if args.psf_fit_range is not None and not 0 <= args.psf_fit_range[0] < args.psf_fit_range[1]:
        parser.error("--psf-fit-range needs 0 <= START < STOP")
    if args.csm_workers < 1 or (args.csm_workers > 1 and args.csm_device >= 0):
        parser.error("--csm-workers must be positive and needs --csm-device -1 when above 1")
    if args.l1_threshold_multiple is not None and not 0 < args.l1_threshold_multiple < np.inf:
        parser.error("--l1-threshold-multiple must be positive and finite")
    if args.l1_wavelet_levels < 1 or args.l1_max_iterations < 1 or not 0 < args.l1_tolerance < 1:
        parser.error("L1 wavelet levels and iterations must be positive; --l1-tolerance in (0, 1)")
    return args


def resolve_inputs(args):
    """Resolve every input file, including the default sidecar locations.

    Args:
        args: Parsed command-line arguments.

    Returns:
        dict: ``{"calibration": {"twix", "seq", "labels"}, "tse": {"twix",
        "seq", "peorder"}}`` with resolved existing paths.

    Raises:
        FileNotFoundError: If an input is missing.
        ValueError: If a default sidecar location is missing or ambiguous.
    """
    calibration_seq = args.calibration_seq.resolve(strict=True)
    labels = args.calibration_labels or calibration_seq.with_name(
        calibration_seq.stem + "_geometry_labels.mat")
    tse_seq = args.tse_seq.resolve(strict=True)
    peorder = args.tse_peorder
    if peorder is None:
        # MB2 writes <out>/metadata/<name>_PEorder.mat, MB1 writes <out>/<name>_PEorder.mat,
        # while the sequences themselves are written to <out>/v151/.
        name = tse_seq.stem + "_PEorder.mat"
        folders = (tse_seq.parent, tse_seq.parent / "metadata", tse_seq.parent.parent,
                   tse_seq.parent.parent / "metadata")
        candidates = sorted({(folder / name).resolve() for folder in folders if (folder / name).exists()})
        if len(candidates) != 1:
            raise ValueError(f"Expected one {name} near the TSE sequence, found {len(candidates)}; "
                             "pass --tse-peorder")
        peorder = candidates[0]
    return {"calibration": {"twix": args.calibration_twix.resolve(strict=True), "seq": calibration_seq,
                            "labels": Path(labels).resolve(strict=True)},
            "tse": {"twix": args.tse_twix.resolve(strict=True), "seq": tse_seq,
                    "peorder": Path(peorder).resolve(strict=True)}}


def output_folders(root):
    """Create the typed artifact subfolders of one output folder.

    Args:
        root: Output folder confirmed by the user on the command line.

    Returns:
        dict[str, Path]: Resolved ``arrays``, ``cache``, ``nifti``,
        ``figures``, ``reports`` and ``logs`` folders.

    Raises:
        ValueError: If a subfolder is a symlink that leaves ``root``.
    """
    root = Path(root).resolve()
    folders = {name: (root / name).resolve() for name in ARTIFACT_FOLDERS}
    for path in folders.values():
        if path.parent != root:
            raise ValueError(f"Artifact folder symlink escapes {root}: {path}")
        path.mkdir(parents=True, exist_ok=True)
    return folders


def start_log(folders):
    """Send progress messages to stdout and to a new log file of this run.

    Args:
        folders: Output folders; the log is ``logs/run_<timestamp>.log``.
    """
    path = folders["logs"] / f"run_{time.strftime('%Y%m%d_%H%M%S')}.log"
    handlers = [logging.StreamHandler(sys.stdout), logging.FileHandler(path, mode="x")]
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s", handlers=handlers,
                        force=True)
    LOGGER.info("Command: %s", " ".join(sys.argv))


def require_free_space(path, gib):
    """Raise before writing when the filesystem of ``path`` has less than ``gib`` GiB free."""
    if shutil.disk_usage(path).free < gib * 1024**3:
        raise RuntimeError(f"Less than {gib} GiB free below {path}; stopping before new outputs")


def digest(path):
    """Return the SHA-256 hex digest of a file."""
    sha = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 24), b""):
            sha.update(block)
    return sha.hexdigest()


def describe_inputs(paths):
    """Return JSON provenance for input files.

    Args:
        paths: Mapping of role to file path.

    Returns:
        dict: Per role the resolved path, size and modification time, plus the
        SHA-256 for sequence and sidecar files (TWIX files are too large).
    """
    description = {}
    for role, path in paths.items():
        stat = path.stat()
        description[role] = {"path": str(path), "bytes": stat.st_size, "mtime_ns": stat.st_mtime_ns,
                             "sha256": None if path.suffix == ".dat" else digest(path)}
    return description


def record_source_digest(folders):
    """Record the SHA-256 of this script and its utilities for the current run.

    Args:
        folders: Output folders; writes ``reports/source_<hash>.json`` once
            per distinct source state.
    """
    here = Path(__file__).resolve()
    sources = [here] + sorted((here.parent / "utils").glob("*.py"))
    value = {str(path): digest(path) for path in sources}
    key = hashlib.sha256(json.dumps(value, sort_keys=True).encode()).hexdigest()[:12]
    ensure_json(folders["reports"] / f"source_{key}.json", value)


def json_ready(value):
    """Convert NumPy scalars/arrays and tuples to JSON-native types, recursively."""
    if isinstance(value, dict):
        return {str(key): json_ready(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_ready(item) for item in value]
    if isinstance(value, np.ndarray):
        return json_ready(value.tolist())
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Path):
        return str(value)
    return value


def save_json(path, value):
    """Write a new JSON report exclusively; an existing file raises FileExistsError."""
    with Path(path).open("x") as handle:
        json.dump(json_ready(value), handle, indent=2)


def save_npz(path, **arrays):
    """Write named arrays exclusively in NumPy NPZ format."""
    with Path(path).open("xb") as handle:
        np.savez(handle, **arrays)


def save_npy(path, array):
    """Write one array exclusively in NumPy NPY format, without pickling."""
    with Path(path).open("xb") as handle:
        np.save(handle, array, allow_pickle=False)


def ensure_json(path, value):
    """Create a JSON report or require an existing one to hold the same value.

    Used for provenance and contract reports whose content is deterministic.

    Raises:
        ValueError: If the existing report differs, i.e. the folder belongs to
            other inputs, settings or results.
    """
    value = json.loads(json.dumps(json_ready(value)))
    if Path(path).exists():
        if json.loads(Path(path).read_text()) != value:
            raise ValueError(f"Existing provenance differs: {path}")
    else:
        save_json(path, value)


def save_json_if_absent(path, value):
    """Write a numerical evidence report unless an earlier run already wrote it.

    Recomputed evidence can differ in the last floating-point digits, for
    example with another thread count; the first report is kept.
    """
    if not Path(path).exists():
        save_json(path, value)


def relative_norm(value, reference):
    """Return ``||value|| / ||reference||`` for complex tensors, accumulated in float64."""
    return float(torch.sqrt(torch.sum(abs(value).double()**2) /
                            torch.sum(abs(reference).double()**2)).cpu())


def native_rows(nx, nx_os):
    """Return the slice of the nominal readout FOV inside the oversampled readout."""
    if nx_os % nx or (nx_os - nx) % 2:
        raise ValueError(f"Oversampled readout {nx_os} is not a centered multiple of {nx}")
    start = (nx_os - nx) // 2
    return slice(start, start + nx)


def phase_coordinates_m(ny, fov_y):
    """Return the image-domain phase-encoding coordinates [m] of a centered FFT grid."""
    return (np.arange(ny) - ny // 2) * fov_y / ny


def csm_acs_start(meta):
    """Return the zero-based physical ky index of the first CSM calibration line."""
    first = meta["csmAdcIndices"][0, 0]
    # kyPhysicalIndex is one-based in the MATLAB sidecar.
    return int(meta["acqTable"][first - 1]["kyPhysicalIndex"]) - 1


def sequence_details(path):
    """Read a Pulseq file and return its ADC labels and excitation parameters.

    Args:
        path: Pulseq ``.seq`` file.

    Returns:
        tuple: ``(sequence, labels, adc_phase, carrier_hz, slice_gradient)``.
        ``labels`` holds the label values at every ADC; the three arrays give,
        per ADC, the ADC phase offset [rad] and the scalar frequency offset
        [Hz] and median slice-gradient amplitude [Hz/m] of the preceding
        excitation.

    Raises:
        ValueError: If an excitation has no colocated Gz.
    """
    sequence = pp.Sequence()
    sequence.read(str(path), remove_duplicates=False)
    labels = sequence.evaluate_labels(evolution="adc")
    phases, carriers, gradients = [], [], []
    last_rf = None
    for block_id in sequence.block_events:
        block = sequence.get_block(block_id)
        if block.rf is not None and block.rf.use == "excitation":
            gz = block.gz
            if gz is None:
                raise ValueError("Excitation has no colocated Gz")
            amplitude = float(gz.amplitude) if gz.type == "trap" else float(np.median(gz.waveform))
            last_rf = (float(block.rf.freq_offset), amplitude)
        if block.adc is not None:
            phases.append(float(block.adc.phase_offset))
            carriers.append(last_rf[0])
            gradients.append(last_rf[1])
    return sequence, labels, np.asarray(phases), np.asarray(carriers), np.asarray(gradients)


def header_contract(scan, sequence_path, meta):
    """Validate a TWIX header against its sequence and the calibration geometry.

    Args:
        scan: Header-only mapVBVD measurement.
        sequence_path: Pulseq file expected to have produced the data.
        meta: Compact calibration sidecar (matrix and FOV).

    Returns:
        dict: Scanner-coordinate stack center ``center_sct_mm``, in-plane
        rotation, receive-element identities, coil count, frequency, FOV and
        the coil insertion timestamps (recorded, not compared).

    Raises:
        ValueError: On a different recorded sequence, readout length, FOV,
            nontransverse prescription or missing coil identities.
    """
    yaps = scan.hdr["MeasYaps"]
    recorded = str(yaps[("sWipMemBlock", "tFree")]).strip('"').replace("\\", "/")
    if Path(recorded).name != Path(sequence_path).name:
        raise ValueError(f"Recorded sequence {recorded} differs from {Path(sequence_path).name}")
    stream = scan.image
    if int(stream.NCol) != int(meta["Nx_os"]) or getattr(stream, "isBrokenFile", False):
        raise ValueError("Unexpected readout length or broken TWIX file")
    prefix = ("sSliceArray", "asSlice", "0")
    fov_mm = [float(yaps[prefix + (key,)]) for key in ("dReadoutFOV", "dPhaseFOV")]
    normal = [float(yaps.get(prefix + ("sNormal", key), 0)) for key in ("dSag", "dCor", "dTra")]
    if not np.allclose(fov_mm, np.asarray(meta["fov"], float) * 1e3, atol=1e-3):
        raise ValueError(f"Prescribed FOV {fov_mm} mm differs from the calibration")
    if not np.allclose(normal, [0, 0, 1], atol=1e-5):
        raise ValueError(f"Only transverse prescriptions are supported, normal {normal}")
    # Insertion timestamps change between scans; every identity, order,
    # connection and selection field must match instead.
    coils = {str(k): str(v) for k, v in yaps.items()
             if "sCoilSelectMeas" in k and "asList" in k and k[-1] != "uiInsertionTime"}
    timestamps = {str(k): str(v) for k, v in yaps.items()
                  if "sCoilSelectMeas" in k and "asList" in k and k[-1] == "uiInsertionTime"}
    if not coils:
        raise ValueError("Missing receive-element identities")
    return {"center_sct_mm": np.mean(np.unique(stream.slicePos[:, :3], axis=0), axis=0).tolist(),
            "rotation_rad": float(yaps.get(prefix + ("dInPlaneRot",), 0)),
            "coils": coils, "physical_coils": int(stream.NCha), "fov_mm": fov_mm,
            "frequency_hz": float(yaps[("sTXSPEC", "asNucleusInfo", "0", "lFrequency")]),
            "coil_insertion_timestamps": timestamps}


def audit_calibration(paths, scan, record_index, meta, folders):
    """Validate the compact calibration and save its trajectory evidence.

    Checks the sequence signature, the compact ADC labels, line-independent
    Wave trajectory deltas, the CSM readout/ky grid of every slice and the
    negative Fourier-z convention of the direct slices.

    Args:
        paths: Calibration inputs (``seq``).
        scan: Header-only calibration measurement.
        record_index: Global-LIN record index of the calibration streams.
        meta: Compact calibration sidecar.
        folders: Calibration output folders.

    Returns:
        dict: ``delta_y`` and ``delta_z`` (Wave minus no-Wave k-space per
        readout sample [1/m]) and ``csm_kx`` (CSM readout kx [1/m]). Cached
        in ``cache/calibration_encoding.npz``.

    Raises:
        ValueError: If any calibration contract fails.
    """
    cache = folders["cache"] / "calibration_encoding.npz"
    if cache.exists():
        return dict(np.load(cache, allow_pickle=False))
    LOGGER.info("Audit calibration trajectory and slice direction")
    nx_os, ny = int(meta["Nx_os"]), int(meta["Ny"])
    fov_y = float(meta["fov"][1])
    seq, labels, _, _, _ = sequence_details(paths["seq"])
    if seq.signature_value != meta["calibrationMetadata"]["SequenceSignature"]:
        raise ValueError("Calibration sequence signature differs from its sidecar")
    if not np.array_equal(labels["LIN"], np.arange(meta["expectedAdcCount"])):
        raise ValueError("Calibration ADC chronology differs from the compact LIN order")
    if not np.array_equal(labels["REF"], [record["isRef"] for record in meta["acqTable"]]):
        raise ValueError("Calibration REF routing differs from its sidecar")
    if any(np.any(labels[key]) for key in ("SLC", "PAR", "SET", "ECO")):
        raise ValueError("Calibration uses noncompact storage labels")
    # (ADC, axis, readout sample) trajectory of the exported sequence.
    trajectory = seq.calculate_kspace()[0].reshape(3, -1, nx_os).transpose(1, 0, 2)
    result = {}
    for axis, first in (("y", 0), ("z", 2)):
        n = int(meta["psfValidLengths"][first])
        nowave, wave = meta["psfAdcIndices"][first:first + 2, :n] - 1
        column = 1 if axis == "y" else 2
        delta = trajectory[wave, column] - trajectory[nowave, column]
        if np.max(np.ptp(delta, axis=0)) > .02:
            raise ValueError(f"Wave calibration {axis} trajectory is line-dependent")
        result[f"delta_{axis}"] = delta.mean(axis=0)
    rows = meta["csmAdcIndices"] - 1
    result["csm_kx"] = trajectory[rows[0, 0], 0].copy()
    acs_start = csm_acs_start(meta)
    expected_ky = (np.arange(acs_start, acs_start + rows.shape[1]) - ny // 2) / fov_y
    for row in rows:
        if not np.allclose(trajectory[row, 0], result["csm_kx"], atol=.02, rtol=0):
            raise ValueError("Calibration CSM slices differ in kx")
        if not np.allclose(trajectory[row, 1], expected_ky[:, None], atol=.02, rtol=0):
            raise ValueError("Calibration CSM lines are not the centered physical ky grid")
    del seq, trajectory
    gc.collect()
    direction = compare_direct_slice_fourier_z(scan, record_index, meta)
    save_json_if_absent(folders["reports"] / "calibration_direct_vs_fourier_z.json", direction)
    negative = direction["hypotheses"]["-1"]["median_supported_correlation"]
    positive = direction["hypotheses"]["1"]["median_supported_correlation"]
    if negative < .95 or negative - positive < .2:
        raise ValueError(f"Calibration does not establish the negative Fourier-z convention: "
                         f"{negative}, {positive}")
    save_npz(cache, **result)
    return result


def audit_tse(paths, scan, meta, geometry, cal_encoding, folders, allowed_missing_adcs):
    """Validate the TSE acquisition against its sequence, sidecar and calibration.

    Derives the raw-SLI to physical-group mapping from the excitation RF and
    slice gradient (or the RF waveform modulation when the carrier is zero),
    checks it against the scanner MDH slice positions, and builds the CAIPI
    and ADC phase table and the sampling mask of every group.

    Args:
        paths: TSE inputs (``seq``, ``peorder``).
        scan: Header-only TSE measurement.
        meta: Compact calibration sidecar.
        geometry: Calibration ``header_contract`` result.
        cal_encoding: ``audit_calibration`` result.
        folders: Output folders of this TSE scan.
        allowed_missing_adcs: Largest accepted number of missing final ADCs.

    Returns:
        tuple: ``(encoding, audit)``. ``encoding`` holds ``phase`` (group,
        band, Ny) complex64, ``mask`` (group, Ny) float32, ``mapping`` (raw
        SLI -> group) and ``pairs`` (group, band) zero-based physical slice
        indices; ``audit`` is the JSON acquisition report. Both are cached.

    Raises:
        ValueError: If any contract or gate fails.
    """
    cache = folders["cache"] / "encoding.npz"
    report_path = folders["reports"] / "acquisition_audit.json"
    if cache.exists() and report_path.exists():
        return dict(np.load(cache, allow_pickle=False)), json.loads(report_path.read_text())
    LOGGER.info("Audit TSE acquisition %s", paths["twix"].name)
    nx, ny, nx_os, nslices = (int(meta[key]) for key in ("Nx", "Ny", "Nx_os", "Nslices"))
    fov = np.asarray(meta["fov"], float)
    header = header_contract(scan, paths["seq"], meta)
    if header["coils"] != geometry["coils"]:
        raise ValueError("Calibration and TSE receive-element identities differ")
    if not np.allclose(header["center_sct_mm"], geometry["center_sct_mm"], atol=1e-3):
        raise ValueError("Calibration and TSE stack centers differ")
    if not np.isclose(header["rotation_rad"], geometry["rotation_rad"], atol=1e-6):
        raise ValueError("Calibration and TSE in-plane rotations differ")

    pe = loadmat(paths["peorder"], simplify_cells=True)
    positions = np.asarray(meta["slicePositions"], float)
    if not np.allclose(np.sort(np.asarray(pe["slicePositions"], float)), positions, atol=1e-10):
        raise ValueError("Calibration and TSE physical slice positions differ")
    if not np.isclose(float(pe["sliceThickness"]), float(meta["sliceThickness"]), atol=1e-12):
        raise ValueError("Calibration and TSE slice thicknesses differ")
    fov_key = "fov" if "fov" in pe else "iceFov"
    if not np.allclose(np.asarray(pe[fov_key], float)[:2], fov, atol=1e-9):
        raise ValueError("Calibration and TSE in-plane FOVs differ")
    mb = int(pe.get("SMSFactor", 1))
    if mb == 2:
        pairs = np.asarray(meta["smsGroups"], int) - 1
        if not np.array_equal(np.asarray(pe["smsGroups"], int) - 1, pairs):
            raise ValueError("Calibration and TSE SMS pairing differ")
    elif mb == 1:
        pairs = np.arange(nslices)[:, None]
    else:
        raise ValueError(f"Unsupported SMS factor {mb}")
    wave_y, wave_z = bool(pe.get("isUseWave_sin", 0)), bool(pe.get("isUseWave_cos", 0))
    if mb == 1 and (wave_y or wave_z):
        raise ValueError("MB1 reconstruction supports complete no-Wave data only")
    if wave_y != wave_z:
        raise ValueError("MB2 Wave reconstruction needs both the y-sine and the z-cosine Wave")
    is_wave = wave_y and wave_z
    if is_wave:
        for key in ("Ncycles", "gwave_max", "wavePolarity"):
            if not np.isclose(float(pe[key]), float(meta[key])):
                raise ValueError(f"TSE and calibration Wave {key} differ")
    ngroups = len(pairs)
    centers = positions[pairs].mean(axis=1)

    seq, labels, adc_phase, carrier, gradient = sequence_details(paths["seq"])
    if "sequenceMetadata" in pe and seq.signature_value != pe["sequenceMetadata"]["SequenceSignature"]:
        raise ValueError("TSE sequence signature differs from its sidecar")
    if np.any(labels.get("REF", 0)):
        raise ValueError("TSE sequence contains reference-scan ADCs")
    lin, slc = np.asarray(labels["LIN"], int), np.asarray(labels["SLC"], int)
    stream = scan.image
    acquired = int(stream.NAcq)
    raw_lin, raw_sli = np.asarray(stream.Lin, int), np.asarray(stream.Sli, int)
    missing = len(lin) - acquired
    # A shortened raw file is accepted only as an exact prefix of the sequence ADC order.
    if not 0 <= missing <= allowed_missing_adcs or not np.array_equal(raw_lin, lin[:acquired]):
        raise ValueError(f"Raw ADC chronology is not the sequence order with at most "
                         f"{allowed_missing_adcs} missing final ADCs ({missing} missing)")
    if not np.array_equal(np.unique(slc), np.arange(ngroups)):
        raise ValueError("Sequence SLC labels do not enumerate the slice groups")
    sequence_slc_to_sli = np.full(ngroups, -1, int)
    for label in range(ngroups):
        values = np.unique(raw_sli[slc[:acquired] == label])
        if values.size != 1:
            raise ValueError("A sequence SLC label does not map to one scanner SLI counter")
        sequence_slc_to_sli[label] = values[0]
    if not np.array_equal(np.sort(sequence_slc_to_sli), np.arange(ngroups)):
        raise ValueError("Sequence SLC to scanner SLI is not a bijection")

    slots = np.asarray(pe["imageAdcMask"], bool)
    ordered = np.asarray(pe["LINorderImg"], int).T[slots.T]
    if len(np.unique(ordered)) != len(ordered) or ordered.min() < 0 or ordered.max() >= ny:
        raise ValueError("PE sidecar lines are duplicated or outside the matrix")
    for label in range(ngroups):
        if not np.array_equal(lin[slc == label], ordered):
            raise ValueError("Sequence LIN order of a slice group differs from the PE sidecar")

    actual, mapping_report = map_excitations_to_groups(seq, labels, carrier, gradient, pe, centers)
    mapping = np.full(ngroups, -1, int)
    mdh_positions = np.asarray(stream.slicePos)[:, :3]
    mdh_offsets = []
    for sli in range(ngroups):
        use = raw_sli == sli
        groups = np.unique(actual[:acquired][use])
        if groups.size != 1 or not np.array_equal(raw_lin[use], ordered[:use.sum()]):
            raise ValueError("A raw SLI does not hold one slice group in sequence LIN order")
        mapping[sli] = groups[0]
        unique = np.unique(mdh_positions[use], axis=0)
        if unique.shape[0] != 1:
            raise ValueError("Scanner MDH slice position varies within one SLI")
        mdh_offsets.append(unique[0] - np.asarray(header["center_sct_mm"]))
    if not np.array_equal(np.sort(mapping), np.arange(ngroups)):
        raise ValueError("Raw SLI counters do not cover every physical slice group")
    # Independent check: the MDH slice offsets written by the scanner must
    # equal the mapped group centers up to one global sign. The sign is
    # recorded, not assumed: on the Prisma 2026-10-15 data it is -1 for the
    # MB1 conventional-sinc scan and +1 for the MB2 scans. Without a scalar
    # carrier the scanner cannot derive the offsets; all-zero offsets are
    # then reported only.
    mdh_offsets = np.asarray(mdh_offsets)
    expected_offsets = np.zeros_like(mdh_offsets)
    expected_offsets[:, 2] = centers[mapping] * 1e3
    signs = [sign for sign in (1, -1)
             if np.allclose(mdh_offsets, sign * expected_offsets, atol=3e-3, rtol=0)]
    if signs:
        mdh_check = f"MDH slice offsets equal {signs[0]:+d} x the mapped group centers"
    elif mapping_report["method"].startswith("RF waveform") and np.allclose(mdh_offsets, 0, atol=3e-3):
        mdh_check = "MDH slice offsets are all zero (no scalar carrier); not compared"
    else:
        raise ValueError("Scanner MDH slice offsets differ from the mapped group centers for both signs")

    # Encoding tables of the complete sequence; missing final ADCs only clear mask entries.
    trajectory = seq.calculate_kspace()[0].reshape(3, -1, nx_os).transpose(1, 0, 2)
    delta_y = cal_encoding["delta_y"] if is_wave else np.zeros(nx_os)
    delta_z = cal_encoding["delta_z"] if is_wave else np.zeros(nx_os)
    caipi = np.asarray(pe.get("caipiAreaByLin", np.zeros(ny)), float)[lin]
    kz_base = trajectory[:, 2] - delta_z
    kz = kz_base.mean(axis=1)
    errors = {"kx": float(np.max(abs(trajectory[:, 0] - cal_encoding["csm_kx"]))),
              "ky": float(np.max(abs(trajectory[:, 1] - delta_y - (lin[:, None] - ny // 2) / fov[1]))),
              "kz": float(np.max(abs(kz_base - caipi[:, None])))}
    if errors["kx"] > .02 or errors["ky"] > .02 or errors["kz"] > .01 / fov[1]:
        raise ValueError(f"TSE and calibration trajectories do not match: {errors}")
    phase = np.ones((ngroups, mb, ny), np.complex64)
    # Slice phase of each band: CAIPI blip plus residual kz at the band
    # position, minus the ADC demodulation phase.
    phase[actual, :, lin] = np.exp(2j * np.pi * (2 * caipi - kz)[:, None] * positions[pairs[actual]]
                                   - 1j * adc_phase[:, None])
    mask = np.zeros((ngroups, ny), np.float32)
    mask[:, ordered] = 1
    mask[actual[acquired:], lin[acquired:]] = 0
    missing_adcs = [{"adc_index_0based": int(index), "lin": int(lin[index]), "sequence_slc": int(slc[index]),
                     "group_0based": int(actual[index])} for index in range(acquired, len(lin))]

    encoding = {"phase": phase, "mask": mask, "mapping": mapping, "pairs": pairs}
    audit = {"tse_twix": str(paths["twix"]), "image_adc_acquired": acquired, "image_adc_expected": len(lin),
             "missing_final_adcs": missing_adcs, "physical_coils": header["physical_coils"],
             "center_sct_mm": header["center_sct_mm"], "rotation_rad": header["rotation_rad"],
             "frequency_hz": header["frequency_hz"], "calibration_frequency_hz": geometry["frequency_hz"],
             "matrix": [nx, ny, nslices], "readout_samples": nx_os,
             "voxel_mm": [fov[0] * 1e3 / nx, fov[1] * 1e3 / ny, float(meta["sliceThickness"]) * 1e3],
             "MB": mb, "Ry": int(pe["Ry"]), "wave": is_wave, "acquired_lines": ordered.tolist(),
             "raw_sli_to_physical_group": mapping.tolist(), "sequence_slc_to_raw_sli": sequence_slc_to_sli.tolist(),
             "physical_pairs_0based": pairs.tolist(), "physical_mapping": mapping_report,
             "mdh_position_check": mdh_check, "trajectory_max_error_per_m": errors,
             "phase_convention": "exp(+i*2*pi*(2*A-kz_base)*z-i*adc_phase)",
             "wave_z_convention": "negative sidecar slice position, established by the calibration",
             "esp_s": float(pe["TE1"]), "te_s": float(pe["TEeff"]), "tr_s": float(pe["TRActual"]),
             "coil_identity_contract": header["coils"],
             "coil_timestamp_comparison_excluded": {"calibration": geometry["coil_insertion_timestamps"],
                                                    "tse": header["coil_insertion_timestamps"]}}
    ensure_json(report_path, audit)
    save_npz(cache, **encoding)
    return encoding, json.loads(report_path.read_text())


def map_excitations_to_groups(seq, labels, carrier, gradient, pe, centers):
    """Return the slice group excited before every ADC.

    With a scalar excitation carrier the group center is the carrier divided
    by the slice gradient. When every carrier is zero, the generator embeds
    the group offset in the RF waveform: the sidecar ``groupBySlc`` mapping
    is then accepted only if demodulating every excitation at its group
    center recovers one common RF envelope and the opposite sign does not.

    Args:
        seq: Pulseq sequence of the TSE.
        labels: ADC labels of ``seq``.
        carrier: Per-ADC excitation frequency offset [Hz].
        gradient: Per-ADC median excitation slice gradient [Hz/m].
        pe: TSE PE-order sidecar.
        centers: Physical group centers [m], shaped (group,).

    Returns:
        tuple: Per-ADC zero-based group index and a JSON mapping report.

    Raises:
        ValueError: If neither method establishes the mapping.
    """
    if np.any(np.abs(carrier) > 1e-9):
        offset = carrier / gradient
        actual = np.argmin(abs(offset[:, None] - centers), axis=1)
        error = float(np.max(abs(offset - centers[actual])))
        if error > 3e-6:
            raise ValueError(f"RF/Gz physical mapping error {error} m")
        return actual, {"method": "scalar excitation carrier divided by slice gradient",
                        "max_position_error_m": error}
    group_by_slc = np.asarray(pe["groupBySlc"], int) - 1
    actual = group_by_slc[np.asarray(labels["SLC"], int)]
    report = verify_waveform_slice_translation(seq, centers[actual])
    return actual, {"method": "RF waveform modulation at the sidecar groupBySlc centers", **report}


def verify_waveform_slice_translation(seq, adc_positions):
    """Check that each excitation waveform is one envelope translated to its group.

    The waveform of a group at position z equals a common envelope times
    ``exp(-2i*pi*z*m(t))``, with ``m`` the exported Gz moment relative to the
    RF center. The sign follows the Prisma 2026-10-15 measurement, in which a
    waveform translated with ``exp(+2i*pi*z*m(t))`` excited -z of the
    direct-FLASH slice coordinate. The opposite sign must fail.

    Args:
        seq: Pulseq sequence of the TSE.
        adc_positions: Expected group center [m] of every ADC.

    Returns:
        dict: Envelope errors of the accepted and the opposite sign.

    Raises:
        ValueError: If the envelopes do not identify the sign and positions.
    """
    integral = seq.get_gradients()[2].antiderivative()
    errors, opposite_errors = [], []
    template = opposite_template = None
    adc_index, elapsed = 0, 0.
    rf, rf_start, checked = None, None, False
    for block_id in seq.block_events:
        block = seq.get_block(block_id)
        if block.rf is not None and block.rf.use == "excitation":
            rf, rf_start, checked = block.rf, elapsed, False
        if block.adc is not None:
            if not checked:
                position = float(adc_positions[adc_index])
                moments = integral(rf_start + rf.delay + rf.t) - integral(rf_start + rf.delay + rf.center)
                values = (rf.signal * np.exp(2j * np.pi * position * moments),
                          rf.signal * np.exp(-2j * np.pi * position * moments))
                if template is None:
                    template, opposite_template = values
                for value, reference, result in zip(values, (template, opposite_template),
                                                    (errors, opposite_errors)):
                    if value.shape != reference.shape:
                        raise ValueError("Excitation RF envelopes have different lengths")
                    phase = np.vdot(reference, value)
                    phase = phase / max(abs(phase), 1e-30)
                    result.append(float(np.linalg.norm(value - reference * phase) / np.linalg.norm(reference)))
                checked = True
            adc_index += 1
        elapsed += seq.block_durations[block_id]
    report = {"max_envelope_error": max(errors),
              "opposite_sign_median_envelope_error": float(np.median(opposite_errors)),
              "excitations_checked": len(errors)}
    if max(errors) > 1e-3 or np.median(opposite_errors) < .1:
        raise ValueError(f"RF waveform slice translation not verified: {report}")
    return report


def prepare_common_basis(paths, scan, record_index, meta, folders, virtual_coils):
    """Return the shared noise whitener and the whitened coil-compression basis.

    The whitener comes from the calibration NOISE scan. The PCA uses every
    third readout sample of all direct FLASH slices after whitening, so the
    same basis serves the CSMs and every TSE group.

    Args:
        paths: Calibration inputs (``twix``).
        scan: Header-only calibration measurement.
        record_index: Global-LIN record index of the calibration streams.
        meta: Compact calibration sidecar.
        folders: Calibration output folders.
        virtual_coils: Number of retained virtual coils.

    Returns:
        tuple: ``(basis, whitener)``, shaped (coil, virtual coil) and (coil,
        coil); data rows multiply from the left, ``data @ basis``. Cached.

    Raises:
        ValueError: If the noise and image coil counts differ or too many
            virtual coils are requested.
    """
    ncoil = int(scan.image.NCha)
    if not 1 <= virtual_coils <= ncoil:
        raise ValueError(f"Cannot keep {virtual_coils} virtual coils of {ncoil}")
    path = folders["cache"] / "noise_whitener.npy"
    if not path.exists():
        noise = load_twix_noise_samples_coillast(str(paths["twix"]))
        covariance = estimate_noise_covariance(noise)
        if covariance.shape != (ncoil, ncoil):
            raise ValueError("Calibration NOISE and image coil counts differ")
        whitener, _ = make_noise_whitener(covariance)
        error = validate_noise_whitener(covariance, whitener)
        save_json_if_absent(folders["reports"] / "noise_model.json",
                            {"source": str(paths["twix"]), "samples": list(noise.shape),
                             "identity_error": error,
                             "scope": "One shared calibration NOISE transform; no per-TSE gain fitting"})
        if not (folders["cache"] / "noise_covariance.npz").exists():
            save_npz(folders["cache"] / "noise_covariance.npz", covariance=covariance)
        save_npy(path, whitener)
    whitener = np.load(path)
    path = folders["cache"] / "global_coil_basis.npy"
    if path.exists():
        return np.load(path), whitener
    covariance = np.zeros((ncoil, ncoil), np.complex128)
    for physical, row in enumerate(meta["csmAdcIndices"]):
        samples = (read_compact_records(scan, record_index, row)[::3] @ whitener)
        samples = samples.reshape(-1, ncoil).astype(np.complex128)
        covariance += samples.conj().T @ samples
        LOGGER.info("Coil PCA: physical slice %d/%d", physical + 1, len(meta["csmAdcIndices"]))
    values, vectors = np.linalg.eigh(covariance)
    order = np.argsort(values)[::-1]
    energy = np.cumsum(values[order]) / values.sum()
    basis = (whitener @ vectors[:, order[:virtual_coils]]).astype(np.complex64)
    save_json_if_absent(folders["reports"] / "coil_compression.json",
                        {"physical_coils": ncoil, "virtual_coils": virtual_coils,
                         "retained_energy": float(energy[virtual_coils - 1]),
                         "cumulative_energy": energy.tolist(),
                         "source": "All direct FLASH slices after whitening"})
    save_npy(path, basis)
    return basis, whitener


def estimate_maps(paths, scan, record_index, meta, basis, folders, device, workers):
    """Save unit-RSS crop-0 ESPIRiT maps independently for every physical slice.

    SigPy's CPU ESPIRiT runs on one thread, so with ``workers > 1`` the slices
    are estimated in parallel processes that each reopen the calibration.

    Args:
        paths: Calibration inputs (``twix``, ``labels``), reopened by workers.
        scan: Header-only calibration measurement.
        record_index: Global-LIN record index of the calibration streams.
        meta: Compact calibration sidecar.
        basis: Coil-compression basis from :func:`prepare_common_basis`.
        folders: Calibration output folders; writes
            ``cache/csm_slice_XX.npy`` (virtual coil, Nx, Ny) and
            ``arrays/csm_diagnostics_XX.npz``.
        device: SigPy device index (-1 for CPU).
        workers: Number of parallel CPU processes (1: serial in this process).

    Raises:
        ValueError: If a slice has diagnostics without its map, or a map is
            nonfinite or its coil RSS is not one.
    """
    nslices = len(meta["csmAdcIndices"])
    todo = [p for p in range(nslices) if not (folders["cache"] / f"csm_slice_{p:02d}.npy").exists()]
    partial = [p for p in todo if (folders["arrays"] / f"csm_diagnostics_{p:02d}.npz").exists()]
    if partial:
        raise ValueError(f"CSM diagnostics without maps for physical slices {partial}; move them aside")
    if workers > 1 and len(todo) > 1:
        # Single-threaded numerical libraries in every spawned worker.
        saved = {key: os.environ.get(key) for key in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "OPENBLAS_NUM_THREADS")}
        os.environ.update({key: "1" for key in saved})
        try:
            with ProcessPoolExecutor(max_workers=workers, mp_context=multiprocessing.get_context("spawn")) as pool:
                futures = {pool.submit(estimate_slice_map_worker, p, paths["twix"], paths["labels"], folders,
                                       basis): p for p in todo}
                try:
                    for done, future in enumerate(as_completed(futures), start=nslices - len(todo) + 1):
                        seconds = future.result()
                        LOGGER.info("CSM saved: physical slice %d, %d/%d done, %.0f s", futures[future] + 1,
                                    done, nslices, seconds)
                except BaseException:
                    pool.shutdown(cancel_futures=True)
                    raise
        finally:
            for key, value in saved.items():
                if value is None:
                    os.environ.pop(key, None)
                else:
                    os.environ[key] = value
        return
    for physical in todo:
        # (readout sample, ky line, slice=1, coil) compact ACS of one direct slice.
        data = read_compact_records(scan, record_index, meta["csmAdcIndices"][physical])
        estimate_slice_map(physical, data, basis, meta, folders, device)
        LOGGER.info("CSM saved: physical slice %d/%d", physical + 1, nslices)
        del data
        gc.collect()
        if device >= 0:
            import cupy as cp
            cp.get_default_memory_pool().free_all_blocks()


def estimate_slice_map(physical, data, basis, meta, folders, device):
    """Estimate, validate and save the crop-0 ESPIRiT map of one physical slice.

    Args:
        physical: Zero-based physical slice index.
        data: Compact ACS records (readout sample, ky line, coil).
        basis: Coil-compression basis.
        meta: Compact calibration sidecar.
        folders: Calibration output folders.
        device: SigPy device index (-1 for CPU).

    Raises:
        ValueError: If the map is nonfinite or its coil RSS is not one.
    """
    nx, ny, nx_os = int(meta["Nx"]), int(meta["Ny"]), int(meta["Nx_os"])
    native_rows(nx, nx_os)
    maps, diagnostic = estimate_espirit_csm_2d_slicewise(
        torch.from_numpy(data[:, :, None]), basis, encoded_matrix=(nx, ny),
        acs_start_y=csm_acs_start(meta), readout_os_factor=nx_os // nx, sigpy_device=sp.Device(device),
        calib_width=ESPIRIT_CALIB_WIDTH, crop=ESPIRIT_CROP, return_diagnostics=True)
    maps = maps[..., 0]
    power = np.sum(abs(maps)**2, axis=0)
    if not np.isfinite(maps).all() or np.max(abs(power - 1)) > 1e-4:
        raise ValueError(f"Nonfinite or non-unit-RSS crop-0 maps of physical slice {physical}")
    # The map is written last; it marks the slice as complete.
    save_npz(folders["arrays"] / f"csm_diagnostics_{physical:02d}.npz",
             **{key: value[..., 0] for key, value in diagnostic.items()})
    save_npy(folders["cache"] / f"csm_slice_{physical:02d}.npy", maps)


def estimate_slice_map_worker(physical, twix, labels, folders, basis):
    """Estimate one slice map in a worker process on one CPU thread.

    Args:
        physical: Zero-based physical slice index.
        twix, labels: Calibration TWIX file and compact sidecar.
        folders: Calibration output folders.
        basis: Coil-compression basis.

    Returns:
        float: Seconds spent on the slice, including reopening the TWIX file.
    """
    start = time.time()
    torch.set_num_threads(1)
    meta = load_compact_metadata(labels)
    scan = open_twix(twix)
    data = read_compact_records(scan, index_compact_streams(scan, meta), meta["csmAdcIndices"][physical])
    estimate_slice_map(physical, data, basis, meta, folders, -1)
    return time.time() - start


def prepare_psf(scan, record_index, meta, cal_encoding, folders, whitener, fit_range, c_fallback):
    """Fit the y/z Wave PSF coefficients from the calibration projections.

    Without ``fit_range`` the coefficient processor selects its automatic
    stable interval and the supported phase residual must not exceed 0.25 rad.
    With a reviewed ``fit_range``, samples outside it are held out, and both
    the held-out coefficient error and the phase residual inside and outside
    must not exceed 0.25 rad.

    Args:
        scan: Header-only calibration measurement.
        record_index: Global-LIN record index of the calibration streams.
        meta: Compact calibration sidecar.
        cal_encoding: ``audit_calibration`` result.
        folders: Calibration output folders.
        whitener: Noise whitener of the calibration coils.
        fit_range: ``[start, stop)`` readout samples, or None for automatic.
        c_fallback: Allow the frequency-locked low-amplitude constant fit.

    Returns:
        dict: ``a_processed``, ``b_processed``, ``c_processed`` per readout
        sample [rad]. Cached in ``cache/wave_coefficients_<tag>.npz``, where
        the tag names the fit settings (see :func:`psf_tag`).

    Raises:
        ValueError: If a projection fit or a validation gate fails, also when
            a previous run already failed with the same settings.
    """
    tag = psf_tag(fit_range, c_fallback)
    path = folders["cache"] / f"wave_coefficients_{tag}.npz"
    report_path = folders["reports"] / f"wave_coefficient_fit_{tag}.json"
    if report_path.exists():
        if not json.loads(report_path.read_text())["validation_passed"]:
            raise ValueError(f"The Wave PSF fit {tag} failed before; see {report_path}")
        if not path.exists():
            raise ValueError(f"Partial Wave PSF fit {tag}: {report_path} without {path}")
        return dict(np.load(path, allow_pickle=False))
    fitted = []
    for axis, first in (("y", 0), ("z", 2)):
        n = int(meta["psfValidLengths"][first])
        pair = [torch.from_numpy(read_compact_records(scan, record_index, meta["psfAdcIndices"][row, :n])
                                 @ whitener) for row in (first, first + 1)]
        fov = float(meta["fov"][1]) if axis == "y" else float(meta["psfFovZ"])
        fitted.append(fit_compact_projection(pair[0], pair[1], cal_encoding[f"delta_{axis}"],
                                             meta[f"psf{axis.upper()}Coordinates"], fov))
        del pair
    y, z = fitted
    # Save the projection evidence before curve acceptance, including failed masks.
    diagnostic_path = folders["arrays"] / "wave_projection_diagnostics.npz"
    if not diagnostic_path.exists():
        save_npz(diagnostic_path,
                 y_phase=y["phase_difference"].numpy(), z_phase=z["phase_difference"].numpy(),
                 y_mask=y["fit_mask_full"].numpy(), z_mask=z["fit_mask_full"].numpy(),
                 y_coherence=y["coherence"].numpy(), z_coherence=z["coherence"].numpy(),
                 y_effective_positions=y["effective_positions"].numpy(),
                 z_effective_positions=z["effective_positions"].numpy(),
                 a_raw=y["slope_raw_full"].numpy(), b_raw=z["slope_raw_full"].numpy(),
                 c_y_raw=y["constant_raw_full"].numpy(), c_z_raw=z["constant_raw_full"].numpy())
    save_json_if_absent(folders["reports"] / "wave_projection_support.json",
                        {"y": y["report"], "z": z["report"]})
    lo, hi = fit_range if fit_range is not None else (None, None)
    processed = process_wave_yz_coefficients(
        y["slope_raw_full"], z["slope_raw_full"], y["constant_raw_full"], z["constant_raw_full"],
        lo, hi, 9, int(meta["Ncycles"]),
        projection_quality=None if fit_range is not None else {
            "y": y["fit_quality_full"], "z": z["fit_quality_full"]},
        allow_low_amplitude_c_frequency_locked_fallback=c_fallback)
    lo, hi = processed["report"]["kx_range"]
    raw = [y["slope_raw_full"], z["slope_raw_full"], y["constant_raw_full"] + z["constant_raw_full"]]
    held = None
    if fit_range is not None:
        # Held-out samples are supported calibration samples outside the reviewed interval.
        held = torch.stack([torch.isfinite(value) for value in raw]).all(0)
        held[lo:hi] = False
        if int(held.sum()) < 80:
            raise ValueError("Fewer than 80 supported samples remain outside the reviewed PSF interval")
    holdout = {}
    if held is not None:
        for key, observed in zip(("a_processed", "b_processed", "c_processed"), raw):
            holdout[key] = float(torch.sqrt(torch.mean((processed[key][held] - observed[held])**2)))
    rms = {}
    for axis, fit, slope in (("y", y, "a_processed"), ("z", z, "b_processed")):
        total = y["constant_raw_full"] + z["constant_raw_full"]
        constant = .5 * processed["c_processed"] + fit["constant_raw_full"] - .5 * total
        model = processed[slope][:, None] * fit["coordinate_normalized"][None] + constant[:, None]
        residual = torch.angle(torch.exp(1j * (fit["phase_difference"] - model)))
        weight = fit["weight"] * fit["fit_mask_full"]
        weight = torch.where(torch.isfinite(residual), weight, 0)
        residual = torch.nan_to_num(residual)
        selections = {"fit": slice(lo, hi)}
        if held is not None:
            selections["held_out"] = held
        rms[axis] = {label: float(torch.sqrt((weight[s] * residual[s]**2).sum() / weight[s].sum()))
                     for label, s in selections.items()}
    passed = all(np.isfinite(v) and v <= .25 for v in holdout.values())
    passed &= all(np.isfinite(v) and v <= .25 for axis in rms.values() for v in axis.values())
    report = {**processed["report"], "validation_passed": bool(passed),
              "fit_policy": "automatic interval" if fit_range is None else f"reviewed interval {lo}:{hi}",
              "held_out_samples": None if held is None else int(held.sum()),
              "held_out_coefficient_rmse_rad": holdout, "supported_phase_rms_rad": rms,
              "low_amplitude_c_fallback_allowed": bool(c_fallback)}
    save_json(report_path, report)
    plot_wave_fit(raw, processed, lo, hi, folders["figures"] / f"wave_coefficient_fit_{tag}.png")
    if not passed:
        raise ValueError(f"Wave PSF validation failed: holdout {holdout}, phase {rms}")
    result = {key: processed[key].cpu().numpy() for key in ("a_processed", "b_processed", "c_processed")}
    save_npz(path, **result)
    LOGGER.info("Wave PSF fit %s passed: interval %d:%d, phase RMS %s", tag, lo, hi, rms)
    return result


def psf_tag(fit_range, c_fallback):
    """Return the file tag of one Wave PSF fit setting, e.g. ``auto`` or ``range1120-1520``."""
    tag = "auto" if fit_range is None else f"range{fit_range[0]}-{fit_range[1]}"
    return tag + ("_cfallback" if c_fallback else "")


def plot_wave_fit(raw, processed, lo, hi, path):
    """Save the gated calibration coefficients and the fitted Wave curves.

    Args:
        raw: Observed ``a``, ``b`` and summed ``c`` coefficients per sample.
        processed: Coefficient-processor result.
        lo, hi: Fit interval in readout samples.
        path: New PNG file.
    """
    fig, axes = plt.subplots(3, 1, figsize=(12, 8))
    for ax, key, observed in zip(axes, ("a_processed", "b_processed", "c_processed"), raw):
        ax.plot(observed.numpy(), ".", ms=2, label="Gated calibration observations")
        ax.plot(processed[key].numpy(), "-", lw=1, label="Central sine-line model")
        ax.axvspan(lo, hi, alpha=.15, color="green", label="Fit interval")
        ax.set_ylabel(key + " [rad]")
        ax.legend(fontsize=7)
    axes[-1].set_xlabel("ADC sample index")
    fig.tight_layout()
    with Path(path).open("xb") as handle:
        fig.savefig(handle, format="png", dpi=130)
    plt.close(fig)


def fit_compact_projection(nowave, wave, delta_k, coordinates_m, fov_m):
    """Fit one Fourier projection with absolute noise, coherence and support gates.

    Inputs are (readout sample, encoded position, coil) tensors and physical
    coordinates. The wrapped-line fitter receives only valid samples. Noise
    power comes from the outer 5% of kx at both ends of the same acquisition;
    it is a support estimate, not a substitute whitening covariance.

    Args:
        nowave, wave: Whitened no-Wave and Wave projections.
        delta_k: Wave minus no-Wave k-space per readout sample [1/m].
        coordinates_m: Encoded positions [m].
        fov_m: Encoded FOV [m].

    Returns:
        dict: Raw slope and constant coefficients, fit quality, phase
        difference, masks, weights, coherence, effective position counts and a
        JSON support report.
    """
    reference, measured = (ifftc_dim(x, dim=1) for x in (nowave, wave))
    power = torch.sum(abs(reference)**2, dim=-1)
    wave_power = torch.sum(abs(measured)**2, dim=-1)
    cross = torch.sum(measured * reference.conj(), dim=-1)
    coherence = abs(cross) / torch.sqrt(power * wave_power).clamp_min(1e-30)
    edge = max(1, power.shape[0] // 20)
    noise_power = float(torch.median(torch.cat((power[:edge], power[-edge:])).flatten()))
    threshold = 6 * noise_power
    valid = (power > threshold) & (wave_power > threshold) & (coherence >= 0.6)
    weight = torch.where(valid, power, 0)
    effective = weight.sum(1)**2 / (weight.square().sum(1)).clamp_min(1e-30)
    coord = torch.as_tensor(coordinates_m, dtype=torch.float32)
    low = torch.where(valid, coord[None], torch.inf).min(1).values
    high = torch.where(valid, coord[None], -torch.inf).max(1).values
    span = high - low
    valid &= ((effective >= 6) & (span >= 0.03))[:, None]
    theory = -2 * torch.pi * torch.as_tensor(delta_k, dtype=torch.float32)[:, None] * coord[None]
    phase = torch.angle(cross * torch.exp(-1j * theory))
    gated_phase = torch.where(valid, phase, torch.nan)
    # Normalize only the fit weights so that floating-point epsilon does not
    # dominate small raw amplitudes; phases are unchanged.
    scale = torch.sqrt(power.max()).clamp_min(1e-20)
    fitted = fit_wrapped_phase_lines_2d(
        gated_phase, reference / scale, coord / fov_m,
        mask_mode="none", min_valid_pixels=8, max_masked_threshold=0.95,
        use_previous_fit_as_init=False, initial_coefficients=torch.zeros(2),
        n_irls=10, huber_delta=0.7, verbose=False,
    )
    residual = torch.angle(torch.exp(1j * (phase - fitted["psf_diff_pred"])))
    weight = torch.where(fitted["mask"], power, 0)
    rms = torch.sqrt((weight * torch.nan_to_num(residual)**2).sum(1) / weight.sum(1).clamp_min(1e-30))
    quality = {key: fitted[key] for key in ("skipped", "valid_pixels", "masked_ratio")}
    quality["wrapped_rms"] = rms
    return {"slope_raw_full": fitted["a_fit_all"], "constant_raw_full": fitted["c_fit_all"],
            "fit_quality_full": quality, "phase_difference": phase,
            "fit_mask_full": fitted["mask"], "coordinate_normalized": coord / fov_m,
            "weight": power, "coherence": coherence, "effective_positions": effective,
            "report": {"edge_noise_power": noise_power, "absolute_power_threshold": threshold,
                       "coherence_threshold": 0.6, "minimum_effective_positions": 6,
                       "minimum_physical_span_m": 0.03,
                       "accepted_kx_fraction": float((~fitted["skipped"]).float().mean()),
                       "noise_estimate": "outer 5% kx samples, both ends; not noise prewhitening"}}


def load_group_data(scan, group, basis, encoding, nx_os, ny):
    """Return the compressed k-space of one slice group on its full LIN grid.

    Args:
        scan: Header-only TSE measurement.
        group: Zero-based group index.
        basis: Coil-compression basis (coil, virtual coil).
        encoding: ``audit_tse`` encoding arrays.
        nx_os, ny: Oversampled readout and PE matrix sizes.

    Returns:
        tuple: ``(data, raw_sli)``; data is complex64 (virtual coil, Nx_os, Ny)
        with zeros on unsampled lines.

    Raises:
        ValueError: If the acquired lines differ from the group mask or the
            data are empty or nonfinite.
    """
    sli = int(np.flatnonzero(encoding["mapping"] == group)[0])
    stream = scan.image
    indices = np.flatnonzero(np.asarray(stream.Sli, int) == sli)
    lin = np.asarray(stream.Lin, int)[indices]
    if not np.array_equal(np.sort(lin), np.flatnonzero(encoding["mask"][group])):
        raise ValueError(f"Acquired lines of group {group} differ from its sampling mask")
    values = read_records(stream, indices) @ basis
    if not np.isfinite(values).all() or not np.any(values):
        raise ValueError(f"Empty or nonfinite measured group {group}")
    data = np.zeros((basis.shape[1], nx_os, ny), np.complex64)
    data[:, :, lin] = values.transpose(2, 0, 1)
    return data, sli


def group_sensitivities(physical, calibration_folders, nx_os):
    """Return the oversampled-readout sensitivities of the bands of one group.

    Args:
        physical: Zero-based physical slice indices of the bands.
        calibration_folders: Calibration output folders with the CSM cache.
        nx_os: Oversampled readout size.

    Returns:
        torch.Tensor: complex64 (band, virtual coil, Nx_os, Ny), zero outside
        the native readout rows.
    """
    maps = [np.load(calibration_folders["cache"] / f"csm_slice_{p:02d}.npy") for p in physical]
    return torch.stack([build_oversampled_sens(m[..., None], nx_os)[..., 0] for m in maps])


def wave_psf(physical, meta, cal_encoding, psf_fit, ny):
    """Return the hybrid-space Wave PSF of one SMS group.

    Args:
        physical: Zero-based physical slice indices of the bands.
        meta: Compact calibration sidecar.
        cal_encoding: ``audit_calibration`` result (theoretical deltas).
        psf_fit: ``prepare_psf`` coefficients.
        ny: PE matrix size.

    Returns:
        numpy.ndarray: complex64 (band, Nx_os, Ny).
    """
    fov_y = float(meta["fov"][1])
    y_m = phase_coordinates_m(ny, fov_y)
    # Wave z is the negative sidecar slice position, as established by the
    # calibration's direct-slice versus Fourier-z test.
    z = -np.asarray(meta["slicePositions"], float)[physical, None, None]
    angle = -2 * np.pi * (cal_encoding["delta_y"][None, :, None] * y_m[None, None]
                          + cal_encoding["delta_z"][None, :, None] * z)
    angle += (psf_fit["a_processed"][None, :, None] * y_m[None, None] / fov_y
              + psf_fit["b_processed"][None, :, None] * z / float(meta["psfFovZ"])
              + psf_fit["c_processed"][None, :, None])
    return np.exp(1j * angle).astype(np.complex64)


def group_terms(scan, group, meta, basis, calibration_folders, encoding, cal_encoding, psf_fit, audit, device):
    """Return the measured data and the encoding terms of one slice group.

    Args:
        scan: Header-only TSE measurement.
        group: Zero-based group index.
        meta: Compact calibration sidecar.
        basis: Coil-compression basis.
        calibration_folders: Calibration output folders (CSM cache).
        encoding: ``audit_tse`` encoding arrays.
        cal_encoding: ``audit_calibration`` result.
        psf_fit: ``prepare_psf`` coefficients or None without Wave.
        audit: ``audit_tse`` report.
        device: Torch device of the tensors.

    Returns:
        dict: Tensors ``data`` (virtual coil, Nx_os, Ny), ``sens`` (band,
        virtual coil, Nx_os, Ny), ``phase`` (band, Ny), ``psf`` (band, Nx_os,
        Ny; ones without Wave) and ``mask`` (1, 1, Ny), plus ``raw_sli``,
        the ``physical`` slice indices and the sampled ``lines``.
    """
    nx_os, ny = int(meta["Nx_os"]), int(meta["Ny"])
    physical = encoding["pairs"][group]
    data, sli = load_group_data(scan, group, basis, encoding, nx_os, ny)
    psf = np.ones((len(physical), nx_os, ny), np.complex64)
    if audit["wave"]:
        psf = wave_psf(physical, meta, cal_encoding, psf_fit, ny)
    return {"data": torch.as_tensor(data, device=device),
            "sens": group_sensitivities(physical, calibration_folders, nx_os).to(device),
            "phase": torch.as_tensor(encoding["phase"][group], device=device),
            "psf": torch.as_tensor(psf, device=device),
            "mask": torch.as_tensor(encoding["mask"][group][None, None], device=device),
            "raw_sli": sli, "physical": physical, "lines": np.flatnonzero(encoding["mask"][group] > 0)}


def mb1_least_squares(data, sens, phase):
    """Return the exact least-squares MB1 image of a complete Cartesian grid.

    Args:
        data: Measured k-space (virtual coil, Nx_os, Ny).
        sens: Sensitivities (1, virtual coil, Nx_os, Ny).
        phase: Slice phase (1, Ny).

    Returns:
        tuple: ``(image, prediction)``; image (1, Nx_os, Ny) and the k-space
        predicted by it.
    """
    coils = ifftc_dim(ifftc_dim(data * phase[0].conj()[None, None], 1), 2)
    power = torch.sum(abs(sens[0])**2, dim=0)
    image = ((sens[0].conj() * coils).sum(0) / power.clamp_min(1e-12))[None]
    prediction = fftc_dim(fftc_dim(sens[0] * image[0], 1), 2) * phase[0][None, None]
    return image, prediction


def verify_mb1_calibration_mapping(scan, basis, meta, calibration_folders, folders, encoding):
    """Check five fully sampled MB1 slices against the stated and reversed FLASH maps.

    Only a global slice-axis reversal is compared, never per-voxel fitting or
    other permutations. The stated mapping must win on all five slices and
    win clearly (residual below 0.4 and below half the reversed one) on the
    second and fourth, which lie inside the well-supported stack.

    Args:
        scan: Header-only TSE measurement.
        basis: Coil-compression basis.
        meta: Compact calibration sidecar.
        calibration_folders: Calibration output folders (CSM cache).
        folders: TSE output folders; writes
            ``reports/mb1_flash_mapping_validation.json``.
        encoding: ``audit_tse`` encoding arrays.

    Raises:
        ValueError: If saved evidence is incompatible or the check fails.
    """
    path = folders["reports"] / "mb1_flash_mapping_validation.json"
    if path.exists():
        report = json.loads(path.read_text())
        if not report["passed"] or report["raw_sli_to_physical"] != encoding["mapping"].tolist():
            raise ValueError("Saved MB1 mapping evidence is incompatible")
        return
    nx, ny, nx_os, nslices = (int(meta[key]) for key in ("Nx", "Ny", "Nx_os", "Nslices"))
    rows = native_rows(nx, nx_os)
    slices = sorted({int(round(v)) for v in np.linspace(0, nslices - 1, 5)})
    results = []
    for sli in slices:
        group = int(encoding["mapping"][sli])
        physical = int(encoding["pairs"][group][0])
        data, _ = load_group_data(scan, group, basis, encoding, nx_os, ny)
        data = torch.from_numpy(data) * torch.from_numpy(encoding["phase"][group, 0].conj())[None, None]
        coils = ifftc_dim(ifftc_dim(data, 1), 2)[:, rows]
        scores = []
        for candidate in (physical, nslices - 1 - physical):
            sens = torch.from_numpy(np.load(calibration_folders["cache"] / f"csm_slice_{candidate:02d}.npy"))
            image = (sens.conj() * coils).sum(0) / torch.sum(abs(sens)**2, 0).clamp_min(1e-12)
            scores.append(relative_norm(sens * image - coils, coils))
        results.append({"raw_sli": sli, "physical_index": physical,
                        "stated_mapping_residual": scores[0], "reversed_mapping_residual": scores[1]})
    passed = all(r["stated_mapping_residual"] < r["reversed_mapping_residual"] for r in results)
    for r in results[1:4:2]:
        passed &= r["stated_mapping_residual"] < .4 and \
            r["stated_mapping_residual"] < .5 * r["reversed_mapping_residual"]
    report = {"passed": bool(passed), "raw_sli_to_physical": encoding["mapping"].tolist(), "slices": results,
              "method": "Full-grid native-FOV coil-vector projection onto fixed FLASH CSMs",
              "limitations": "Global reversal check; not an independent absolute scanner profile validation",
              "basis_sha256": digest(calibration_folders["cache"] / "global_coil_basis.npy")}
    save_json(path, report)
    if not passed:
        raise ValueError(f"MB1/FLASH physical mapping not established: {results}")


def operator_tests(sens, phase, psf, mask, folders, max_iterations, tolerance):
    """Require real-grid adjoint and synthetic-recovery checks of the MB2 operator.

    Args:
        sens, phase, psf, mask: Encoding of the first measured group.
        folders: TSE output folders; writes ``reports/operator_tests.json``.
        max_iterations, tolerance: CG settings of the measured groups.

    Raises:
        ValueError: If the adjoint error exceeds 1e-5, the synthetic data
            residual exceeds 1e-3 or CG does not converge.
    """
    path = folders["reports"] / "operator_tests.json"
    if path.exists():
        return
    generator = torch.Generator(device="cpu").manual_seed(20261015)
    shape_x, shape_y = (sens.shape[0], *sens.shape[2:]), sens.shape[1:]
    x = torch.randn(shape_x, dtype=torch.complex64, generator=generator).to(sens.device)
    y = torch.randn(shape_y, dtype=torch.complex64, generator=generator).to(sens.device)
    ax = mb2_wave_forward(x, sens, phase, psf, mask)
    ahy = mb2_wave_adjoint(y, sens, phase, psf, mask)
    lhs = (ax.conj().to(torch.complex128) * y).sum()
    rhs = (x.conj().to(torch.complex128) * ahy).sum()
    adjoint = float((abs(lhs - rhs) / torch.maximum(abs(lhs), abs(rhs))).cpu())
    del y, ahy
    recovered, info = cg_sense_mb2_wave_2d(ax, sens, phase, psf, mask, n_iter=max_iterations,
                                           tol=tolerance, verbose=False, return_info=True)
    residual = relative_norm(mb2_wave_forward(recovered, sens, phase, psf, mask) - ax, ax)
    report = {"adjoint_error": adjoint, "synthetic_data_residual": residual, "solver": info}
    if adjoint > 1e-5 or residual > 1e-3 or not info["converged"]:
        save_json(folders["reports"] / f"operator_tests_failed_{time.strftime('%Y%m%d_%H%M%S')}.json", report)
        raise ValueError(f"MB2 operator tests failed: {report}")
    save_json(path, report)


def reconstruct_groups(scan, meta, basis, calibration_folders, folders, encoding, cal_encoding,
                       psf_fit, audit, args):
    """Reconstruct every slice group, saving checkpoints, and assemble the volume.

    MB1 groups use :func:`mb1_least_squares`; MB2 groups use lambda-0
    CG-SENSE with the Wave PSF (or a unit PSF without Wave). Existing group
    checkpoints are reused after their digest and physical indices match.

    Args:
        scan: Header-only TSE measurement.
        meta: Compact calibration sidecar.
        basis: Coil-compression basis.
        calibration_folders: Calibration output folders.
        folders: TSE output folders.
        encoding: ``audit_tse`` encoding arrays.
        cal_encoding: ``audit_calibration`` result.
        psf_fit: ``prepare_psf`` coefficients or None without Wave.
        audit: ``audit_tse`` report.
        args: Parsed arguments (device, iterations, tolerance, free space).

    Returns:
        tuple: complex64 volume (Nx, Ny, physical slice) in physical slice
        order and the list of group reports.

    Raises:
        ValueError: If a checkpoint is inconsistent or a group fails its
            finite/convergence gate.
    """
    nx, ny, nx_os, nslices = (int(meta[key]) for key in ("Nx", "Ny", "Nx_os", "Nslices"))
    rows = native_rows(nx, nx_os)
    device = torch.device(args.device)
    image = np.zeros((nx, ny, nslices), np.complex64)
    reports = []
    basis_digest = digest(calibration_folders["cache"] / "global_coil_basis.npy")
    for group, physical in enumerate(encoding["pairs"]):
        path = folders["arrays"] / f"{SOLVER_TAG}_group_{group:02d}.npy"
        report_path = folders["reports"] / f"{SOLVER_TAG}_group_{group:02d}.json"
        if path.exists() and report_path.exists():
            report = json.loads(report_path.read_text())
            if digest(path) != report["checkpoint_sha256"] or report["physical_indices_0based"] != physical.tolist():
                raise ValueError(f"Changed checkpoint of group {group}: {path}")
            recovered = np.load(path)
        elif path.exists() or report_path.exists():
            raise ValueError(f"Partial checkpoint of group {group}; move {path.name} or "
                             f"{report_path.name} aside or use a new output folder")
        else:
            require_free_space(folders["arrays"], args.min_free_gib)
            terms = group_terms(scan, group, meta, basis, calibration_folders, encoding, cal_encoding,
                                psf_fit, audit, device)
            data, sens, phase, psf, mask = (terms[key] for key in ("data", "sens", "phase", "psf", "mask"))
            if audit["MB"] == 1:
                if audit["wave"] or not np.all(encoding["mask"][group] == 1):
                    raise ValueError("The exact MB1 solution needs a complete no-Wave grid")
                result, prediction = mb1_least_squares(data, sens, phase)
                info = {"method": "exact least-squares coil combination of a complete grid",
                        "converged": True}
            else:
                operator_tests(sens, phase, psf, mask, folders, args.max_iterations, args.tolerance)
                result, info = cg_sense_mb2_wave_2d(data, sens, phase, psf, mask, n_iter=args.max_iterations,
                                                    tol=args.tolerance, lambda_l2=0, verbose=False,
                                                    return_info=True)
                prediction = mb2_wave_forward(result, sens, phase, psf, mask)
            recovered = result[:, rows].cpu().numpy().astype(np.complex64)
            report = {"group_0based": group, "physical_indices_0based": physical.tolist(),
                      "raw_sli": terms["raw_sli"], "sampled_lines": int(encoding["mask"][group].sum()),
                      "solver": info,
                      "relative_data_residual": relative_norm(prediction - data * mask, data * mask),
                      "device": str(device), "shared_basis_sha256": basis_digest}
            if not np.isfinite(recovered).all() or not info["converged"]:
                save_json(folders["reports"] / f"{SOLVER_TAG}_group_{group:02d}_failed_"
                          f"{time.strftime('%Y%m%d_%H%M%S')}.json", report)
                raise ValueError(f"Group {group} failed its finite/convergence gate")
            save_npy(path, recovered)
            report["checkpoint_sha256"] = digest(path)
            save_json(report_path, report)
            LOGGER.info("Group %d/%d physical %s residual %.6f", group + 1, len(encoding["pairs"]),
                        physical.tolist(), report["relative_data_residual"])
            del terms, data, sens, phase, psf, mask, result, prediction
            gc.collect()
            if device.type == "cuda":
                torch.cuda.empty_cache()
        image[:, :, physical] = recovered.transpose(1, 2, 0)
        reports.append(report)
    path = folders["arrays"] / f"{SOLVER_TAG}_complex_physical_slices.npy"
    if not path.exists():
        save_npy(path, image)
    elif not np.array_equal(np.load(path), image):
        raise ValueError("Existing assembled volume differs from the group checkpoints")
    return image, reports


def l1_tag(threshold_multiple, levels, max_iterations, tolerance):
    """Return the file tag of one L1-wavelet setting.

    Args:
        threshold_multiple: ``--l1-threshold-multiple`` C.
        levels, max_iterations, tolerance: FISTA settings.

    Returns:
        str: ``l1c<C>`` with the decimal point written as ``p`` (``l1c0p5``
        for C = 0.5), followed by ``_lev<n>``, ``_it<n>`` or ``_tol<t>`` for
        each FISTA setting that differs from its default.
    """
    tag = "l1c" + f"{threshold_multiple:g}".replace(".", "p")
    if levels != L1_DEFAULT_LEVELS:
        tag += f"_lev{levels}"
    if max_iterations != L1_DEFAULT_MAX_ITERATIONS:
        tag += f"_it{max_iterations}"
    if tolerance != L1_DEFAULT_TOLERANCE:
        tag += f"_tol{tolerance:g}"
    return tag


def check_l1_support(audit, meta, levels):
    """Stop before any reconstruction when L1-wavelet regularization cannot run.

    Args:
        audit: ``audit_tse`` report.
        meta: Compact calibration sidecar (native matrix).
        levels: Periodized wavelet levels.

    Raises:
        ValueError: For MB1 data or a native matrix whose sizes are not
            divisible by ``2**levels``.
    """
    if audit["MB"] != 2:
        raise ValueError("L1-wavelet regularization is implemented for MB2 scans only")
    nx, ny = int(meta["Nx"]), int(meta["Ny"])
    if nx % 2**levels or ny % 2**levels:
        raise ValueError(f"The native {nx} x {ny} matrix does not allow {levels} periodized wavelet levels; "
                         "choose --l1-wavelet-levels so that both sizes are divisible by 2**levels")


